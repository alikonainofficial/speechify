import { useState } from "react";
import { enhanceNote } from "../net/api";

/**
 * "Enhance with AI" for one note: title, summary, tags and a cleaned-up text.
 * Results are stored in note.ai together with the original title and text, so
 * applying the AI title or cleaned text can always be undone.
 *
 * Props: note, onUpdate(id, changes) → updated note or null.
 */
export default function AiPanel({ note, onUpdate }) {
  const [status, setStatus] = useState("idle"); // idle | loading
  const [error, setError] = useState(null);
  const [view, setView] = useState("cleaned"); // which text the comparison shows
  const ai = note.ai;

  const enhance = async () => {
    setStatus("loading");
    setError(null);
    try {
      const result = await enhanceNote(note.text);
      onUpdate(note.id, {
        ai: { ...result, originalTitle: note.title, originalText: note.text, createdAt: new Date().toISOString() },
      });
      setView("cleaned");
    } catch (err) {
      setError(err.message);
    } finally {
      setStatus("idle");
    }
  };

  const usingAiTitle = ai && note.title === ai.title;
  const usingCleanedText = ai && note.text === ai.cleanedText;
  const loading = status === "loading";
  const buttonClass =
    "rounded-lg border border-line bg-surface px-3 py-1.5 text-sm font-medium hover:bg-line/40 disabled:cursor-not-allowed disabled:opacity-50";

  return (
    <section aria-label="AI clean-up" className="flex flex-col gap-4 border-t border-line pt-6">
      <div className="flex flex-wrap items-center gap-3">
        <button
          type="button"
          onClick={enhance}
          disabled={loading || !note.text.trim()}
          className="rounded-lg bg-accent px-4 py-2 text-sm font-semibold text-accent-ink hover:brightness-110 disabled:cursor-not-allowed disabled:opacity-50"
        >
          {loading ? "Enhancing…" : ai ? "Enhance again" : "Enhance with AI"}
        </button>
        <p className="text-sm text-muted">Fixes punctuation, removes filler words, and suggests a title, summary and tags.</p>
      </div>

      {error && (
        <p role="alert" className="text-danger">
          {error}
        </p>
      )}

      {ai && (
        <div className="flex flex-col gap-4" data-testid="ai-result">
          <div>
            <p className="font-semibold">{ai.title}</p>
            <p className="text-muted">{ai.summary}</p>
            {ai.tags.length > 0 && (
              <ul className="mt-2 flex flex-wrap gap-2" aria-label="Tags">
                {ai.tags.map((tag) => (
                  <li key={tag} className="rounded-full bg-accent/10 px-2.5 py-0.5 text-sm text-accent">
                    {tag}
                  </li>
                ))}
              </ul>
            )}
          </div>

          <div className="flex flex-wrap gap-2">
            <button
              type="button"
              className={buttonClass}
              onClick={() => onUpdate(note.id, { title: usingAiTitle ? ai.originalTitle : ai.title })}
            >
              {usingAiTitle ? "Restore original title" : "Use AI title"}
            </button>
            <button
              type="button"
              className={buttonClass}
              onClick={() => onUpdate(note.id, { text: usingCleanedText ? ai.originalText : ai.cleanedText })}
            >
              {usingCleanedText ? "Restore original text" : "Replace text with cleaned version"}
            </button>
          </div>

          <div className="flex flex-col gap-2">
            <div className="flex gap-1" role="group" aria-label="Compare text">
              {[
                ["original", "Original"],
                ["cleaned", "Cleaned"],
              ].map(([value, label]) => (
                <button
                  key={value}
                  type="button"
                  aria-pressed={view === value}
                  onClick={() => setView(value)}
                  className={`rounded-md px-3 py-1 text-sm ${view === value ? "bg-ink text-paper" : "text-muted hover:bg-line/40"}`}
                >
                  {label}
                </button>
              ))}
            </div>
            <p data-testid="ai-compare-text" className="whitespace-pre-wrap rounded-lg bg-surface p-4 font-serif text-lg leading-relaxed">
              {view === "cleaned" ? ai.cleanedText : ai.originalText}
            </p>
          </div>
          <p className="text-xs text-muted">Generated by {ai.model}.</p>
        </div>
      )}
    </section>
  );
}
